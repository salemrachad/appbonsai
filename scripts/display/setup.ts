// The display ESP32's connection: writes firmware/appbonsai_display/secrets.h (gitignored) with the tree's
// address and password from .env.cloud (never printed), keeping the Wi-Fi lines you typed in it, and
// src/assets/roots.h with the root certificates the device trusts for the tree's address.
//
//   npm run display:setup
//
// Then put your Wi-Fi's name and password in secrets.h yourself (they never go through this script).
import { X509Certificate } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { rootCertificates } from 'node:tls';

const DIR = 'firmware/appbonsai_display';
const SECRETS = `${DIR}/secrets.h`;
const ROOTS = `${DIR}/src/assets/roots.h`;

// workers.dev is Let's Encrypt today (ECDSA, to ISRG Root X2); Cloudflare also issues from Google Trust Services
// and SSL.com, and may switch without notice: the roots of all three
const TRUSTED = ['ISRG Root X1', 'ISRG Root X2', 'GTS Root R1', 'GTS Root R4', 'SSL.com TLS ECC Root CA 2022', 'SSL.com TLS RSA Root CA 2022'];

if (existsSync('.env.cloud')) process.loadEnvFile('.env.cloud');
const url = (process.env.APPBONSAI_CLOUD_URL ?? '').replace(/\/+$/, '');
const password = process.env.APPBONSAI_CLOUD_PASSWORD ?? '';
if (!/^https:\/\//.test(url) || !password) {
  console.error('[display] Put APPBONSAI_CLOUD_URL (https://…) and APPBONSAI_CLOUD_PASSWORD in .env.cloud first.');
  process.exit(1);
}

const cString = (s: string) => JSON.stringify(s); // a C string literal for printable ASCII
if (![...url, ...password].every((c) => c >= ' ' && c <= '~')) {
  console.error('[display] The address or password has characters a C string would need escaped; not written.');
  process.exit(1);
}

// Keep the Wi-Fi the user typed
const old = existsSync(SECRETS) ? readFileSync(SECRETS, 'utf8') : '';
const kept = (name: string) => new RegExp(`^#define ${name} (".*")\\s*$`, 'm').exec(old)?.[1] ?? '""';

writeFileSync(
  SECRETS,
  `// The display's connection (gitignored: never commit it). Written by npm run display:setup, which keeps the
// Wi-Fi lines: type your Wi-Fi's name and password here. The tree's address and password come from .env.cloud.
#pragma once
#define WIFI_SSID ${kept('WIFI_SSID')}
#define WIFI_PASSWORD ${kept('WIFI_PASSWORD')}
#define APPBONSAI_URL ${cString(url)}
#define APPBONSAI_PASSWORD ${cString(password)}
`,
);

const roots = TRUSTED.map((cn) => {
  const pem = rootCertificates.find((p) => new RegExp(`CN=${cn.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'm').test(new X509Certificate(p).subject));
  if (!pem) throw new Error(`Node's root store has no ${cn}`);
  return { cn, pem: pem.trim(), until: new X509Certificate(pem).validTo };
});
mkdirSync(`${DIR}/src/assets`, { recursive: true });
writeFileSync(
  ROOTS,
  `// Generated by scripts/display/setup.ts from Node's root store (Mozilla's). Do not edit.
#pragma once
const char ROOTS_PEM[] =
${roots.map((r) => `    // ${r.cn}, until ${r.until}\n${r.pem.split('\n').map((l) => `    "${l}\\n"`).join('\n')}`).join('\n')};
`,
);

const wifi = kept('WIFI_SSID') !== '""';
console.log(`[display] ${SECRETS}: the tree's address and password${wifi ? ', Wi-Fi kept' : '; now type your Wi-Fi name and password in it'}`);
console.log(`[display] ${ROOTS}: ${roots.map((r) => r.cn).join(', ')}`);
